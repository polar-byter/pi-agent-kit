"""Start OpenCode with the model choice for the Master Chief and the executors.

By default both executors are bound to an already loaded LM Studio instance and the
Master Chief keeps the model from the project config. An optional choice file written by the
model configurator (.opencode/kit-models.json) can switch the Master Chief and/or the
executors to another model. Without that file the launcher behaves as before.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

try:
    from .task_control_state import plain_path
    from .check_env import strip_jsonc
    from .lmstudio_models import base_url, configured_model, loaded_models, select_model
    from .opencode_cli import is_wrapper, locate_opencode
except ImportError:
    from task_control_state import plain_path
    from check_env import strip_jsonc
    from lmstudio_models import base_url, configured_model, loaded_models, select_model
    from opencode_cli import is_wrapper, locate_opencode

HEADER = '// Generated by kit/run_opencode.py. Local model selection; do not edit.\n'
ALIAS = 'loaded-executor'

# The model configurator writes the user's choice here; the launcher only reads it.
CHOICES_FILE = 'kit-models.json'
MASTER_CHIEF_AGENTS = ('build', 'plan')
EXECUTOR_AGENTS = ('executor', 'executor-fast')
# Provider IDs that the launcher adds for "own API" choices.
MASTER_CHIEF_PROVIDER = 'kit-master-chief-api'
EXECUTOR_PROVIDER = 'kit-executor-api'
# OpenCode V2 package for any OpenAI-compatible endpoint.
OPENAI_COMPATIBLE = '@opencode/ai/providers/openai-compatible'
ENV_NAME = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')


def find_opencode(command: str) -> str:
    """Return the native OpenCode CLI; the search order is in kit/opencode_cli.py.

    Args:
        command: the command or path to the OpenCode executable ("opencode" = search).
    Raises:
        ValueError: nothing found, or the found file is a .cmd/.bat wrapper.
    """
    executable = locate_opencode(command)
    if not executable:
        raise ValueError('OpenCode CLI not found. Install it or pass --opencode with its path.')
    if is_wrapper(executable):
        raise ValueError('Pass --opencode with the native opencode.exe/opencode-cli.exe path; .cmd/.bat wrappers are not supported.')
    return executable


def _text(section: dict, key: str, where: str) -> str:
    """Return a required non-empty string field or explain which one is wrong."""
    value = section.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'{CHOICES_FILE}: "{where}.{key}" must be a non-empty string')
    return value.strip()


def _api(section: dict, where: str) -> dict:
    """Validate an "own API" choice: endpoint, model and the name of the key variable."""
    url = _text(section, 'baseURL', where)
    if not url.startswith(('http://', 'https://')):
        raise ValueError(f'{CHOICES_FILE}: "{where}.baseURL" must start with http:// or https://')
    key_env = _text(section, 'keyEnv', where)
    if not ENV_NAME.fullmatch(key_env):
        raise ValueError(f'{CHOICES_FILE}: "{where}.keyEnv" must be an environment variable name, not the key itself')
    if not os.environ.get(key_env):
        raise ValueError(f'Environment variable {key_env} with the API key for "{where}" is not set. '
                         'Save the key in the configurator, then open a new terminal.')
    return {'source': 'api', 'baseURL': url.rstrip('/'), 'model': _text(section, 'model', where), 'keyEnv': key_env}


def _opencode(section: dict, where: str) -> dict:
    """A model that OpenCode already knows: "provider/model" from /connect or OpenCode Go."""
    model = _text(section, 'model', where)
    if '/' not in model:
        raise ValueError(f'{CHOICES_FILE}: "{where}.model" must look like provider/model, for example opencode-go/deepseek-v4.1-flash')
    return {'source': 'opencode', 'model': model}


def load_choices(root: Path) -> dict:
    """Read the optional choice file. A missing file or section means the default behaviour.

    Returns {'masterChief': None | {...}, 'executors': None | {...}}.
    Master Chief:     {'source': 'opencode', 'model': 'provider/model'} or an API choice.
    executors: {'source': 'lmstudio', 'instance': str | None},
               {'source': 'opencode', 'model': 'provider/model'} or an API choice.
    """
    path = root / '.opencode' / CHOICES_FILE
    result = {'masterChief': None, 'executors': None}
    if not path.exists():
        config_path = root / 'opencode.jsonc'
        if config_path.is_file():
            config = json.loads(strip_jsonc(config_path.read_text(encoding='utf-8-sig')))
            fixer = config.get('agents', {}).get('bug-fixer', {})
            if fixer.get('disabled') is False and isinstance(fixer.get('model'), str):
                result['bugFixer'] = {'source': 'opencode', 'model': fixer['model']}
        return result
    try:
        data = json.loads(path.read_text(encoding='utf-8-sig'))
    except json.JSONDecodeError as error:
        raise ValueError(f'{CHOICES_FILE} is not valid JSON: {error}') from error
    if not isinstance(data, dict):
        raise ValueError(f'{CHOICES_FILE} must contain a JSON object')
    if 'execution' in data:
        if __package__:
            from .execution_policy import normalize_policy
        else:
            from execution_policy import normalize_policy
        result['execution'] = normalize_policy(data['execution'])
    if data.get('bugFixer') is not None:
        fixer = data['bugFixer']
        if not isinstance(fixer, dict) or fixer.get('source') not in ('opencode', 'api'):
            raise ValueError('bugFixer must select an OpenCode model or own API')
        result['bugFixer'] = _opencode(fixer, 'bugFixer') if fixer['source'] == 'opencode' else _api(fixer, 'bugFixer')

    master_chief = data.get('masterChief')
    if master_chief is not None:
        if not isinstance(master_chief, dict):
            raise ValueError(f'{CHOICES_FILE}: "masterChief" must be an object')
        source = master_chief.get('source')
        if source == 'opencode':
            result['masterChief'] = _opencode(master_chief, 'masterChief')
        elif source == 'api':
            result['masterChief'] = _api(master_chief, 'masterChief')
        else:
            raise ValueError(f'{CHOICES_FILE}: "masterChief.source" must be "opencode" or "api"')

    executors = data.get('executors')
    if executors is not None:
        if not isinstance(executors, dict):
            raise ValueError(f'{CHOICES_FILE}: "executors" must be an object')
        source = executors.get('source')
        if source == 'lmstudio':
            instance = executors.get('instance')
            if instance is not None and (not isinstance(instance, str) or not instance.strip()):
                raise ValueError(f'{CHOICES_FILE}: "executors.instance" must be a non-empty string or absent')
            result['executors'] = {'source': 'lmstudio', 'instance': instance.strip() if instance else None}
        elif source == 'opencode':
            result['executors'] = _opencode(executors, 'executors')
        elif source == 'api':
            result['executors'] = _api(executors, 'executors')
        else:
            raise ValueError(f'{CHOICES_FILE}: "executors.source" must be "lmstudio", "opencode" or "api"')
    return result


def api_provider(choice: dict, name: str) -> dict:
    """Provider entry for an OpenAI-compatible endpoint; the key stays in the environment."""
    return {
        'name': name,
        'env': [choice['keyEnv']],
        'package': OPENAI_COMPATIBLE,
        'settings': {'baseURL': choice['baseURL']},
        'models': {choice['model']: {'name': choice['model']}},
    }


def prepare(root: Path, explicit: str | None = None):
    if __package__:
        from .model_switch import preparation
    else:
        sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
        from kit.model_switch import preparation
    with preparation(root):
        return _prepare(root, explicit)


def _prepare(root: Path, explicit: str | None = None):
    """Write only our local overlay, preserving the source config and agent permissions.

    Returns the selected LM Studio instance, or None when the executors use a model
    from OpenCode or an own API.
    """
    if __package__:
        from .task_metrics import TaskMetrics, pending_attempts
        from .task_control_state import read_state
    else:
        from task_metrics import TaskMetrics, pending_attempts
        from task_control_state import read_state
    for journal in (root / '.metrics').glob('*/events.jsonl'):
        task = journal.parent.name
        events = TaskMetrics(root).read(task)
        if (not any(e['kind'] == 'finish' for e in events)
                and any(e.get('workspace') for e in pending_attempts(events))
                and read_state(root, task).get('status') not in ('cancelled', 'paused')):
            raise ValueError('Finish or cancel isolated work before preparing new model settings; saving a draft is allowed')
    config = json.loads(strip_jsonc((root / 'opencode.jsonc').read_text(encoding='utf-8-sig')))
    choices = load_choices(root)
    default_executor = config.get('agents', {}).get('executor', {}).get('model', '')
    executors = choices['executors'] or ({'source': 'opencode', 'model': default_executor}
                  if default_executor and not default_executor.startswith('lmstudio/') else {'source': 'lmstudio', 'instance': None})
    if executors['source'] != 'lmstudio' and explicit:
        raise ValueError('--model selects an LM Studio instance, but the executors are not set to LM Studio in ' + CHOICES_FILE)
    if executors['source'] == 'lmstudio':
        for name in EXECUTOR_AGENTS:
            agent = config.get('agents', {}).get(name, {})
            if not isinstance(agent.get('model'), str) or not agent['model'].startswith('lmstudio/'):
                raise ValueError(f'{name} must be configured as an LM Studio agent')
    directory = root / '.opencode'
    overlay = directory / 'opencode.jsonc'
    if (directory / 'opencode.json').exists():
        raise ValueError('Existing .opencode/opencode.json: move its settings into the project config before using this launcher')
    if overlay.exists() and not overlay.read_text(encoding='utf-8').startswith(HEADER):
        raise ValueError('Existing .opencode/opencode.jsonc belongs to you; it will not be overwritten. Move its settings into the project config first.')

    patch = {'providers': {}, 'agents': {}}
    prompt_names = {'build': 'master-chief.md', 'executor': 'executor.md',
                    'executor-fast': 'executor-fast.md', 'bug-fixer': 'bug-fixer.md'}
    for agent, filename in prompt_names.items():
        prompt = root / 'kit' / 'prompts' / filename
        if prompt.is_file():
            plain_path(prompt)
            patch['agents'][agent] = {'system': prompt.read_text(encoding='utf-8')}
    model = None
    if executors['source'] == 'lmstudio':
        # Default path: the already loaded instance; --model wins over the saved instance.
        model = select_model(loaded_models(base_url(config)), configured_model(config), explicit or executors['instance'])
        patch['providers']['lmstudio'] = {'models': {ALIAS: {'modelID': model.id, 'name': model.name + ' (already loaded)'}}}
        executor_ref = 'lmstudio/' + ALIAS
    elif executors['source'] == 'opencode':
        # A model OpenCode already knows: no provider is added, only the reference.
        executor_ref = executors['model']
    else:
        patch['providers'][EXECUTOR_PROVIDER] = api_provider(executors, 'Executor API (kit)')
        executor_ref = f"{EXECUTOR_PROVIDER}/{executors['model']}"
    for name in EXECUTOR_AGENTS:
        patch['agents'].setdefault(name, {}).update(model=executor_ref)
    if choices.get('execution'):
        for name in EXECUTOR_AGENTS:
            patch['agents'][name]['steps'] = choices['execution']['maxSteps']
    if choices.get('bugFixer'):
        fixer = choices['bugFixer']
        if fixer['source'] == 'api':
            patch['providers']['kit-bug-fixer-api'] = api_provider(fixer, 'Bug Fixer API (kit)')
            reference = 'kit-bug-fixer-api/' + fixer['model']
        else:
            reference = fixer['model']
        patch['agents'].setdefault('bug-fixer', {}).update(model=reference, disabled=False,
            steps=choices.get('execution', {}).get('fixerMaxSteps', 32))
    elif 'bug-fixer' in config.get('agents', {}):
        patch['agents'].setdefault('bug-fixer', {}).update(disabled=True)

    master_chief = choices['masterChief']
    if master_chief:
        if master_chief['source'] == 'api':
            patch['providers'][MASTER_CHIEF_PROVIDER] = api_provider(master_chief, 'Master Chief API (kit)')
            master_chief_ref = f"{MASTER_CHIEF_PROVIDER}/{master_chief['model']}"
        else:
            master_chief_ref = master_chief['model']
        for name in MASTER_CHIEF_AGENTS:
            patch['agents'].setdefault(name, {}).update(model=master_chief_ref)
        # The main session ("opencode run", a new Desktop chat) starts on the top-level
        # model, not on agents.build.model (checked on OpenCode 2.0.26), so set both.
        patch['model'] = master_chief_ref

    directory.mkdir(exist_ok=True)
    temporary = directory / 'opencode.jsonc.tmp'
    temporary.write_text(HEADER + json.dumps(patch, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    temporary.replace(overlay)
    return model


def describe(root: Path, model) -> str:
    """Human-readable summary of what the overlay now says."""
    choices = load_choices(root)
    lines = []
    if model is not None:
        lines.append(f'Already loaded: {model.name}\nInstance: {model.id}\nBoth executors use this instance; load settings are unchanged.')
    else:
        executors = choices['executors']
        if executors is None:
            config = json.loads(strip_jsonc((root / 'opencode.jsonc').read_text(encoding='utf-8-sig')))
            executors = {'source': 'opencode', 'model': config['agents']['executor']['model']}
        if executors['source'] == 'opencode':
            lines.append(f"Executors: {executors['model']} (model from OpenCode)")
        else:
            lines.append(f"Executors: own API {executors['baseURL']}, model {executors['model']}")
    master_chief = choices['masterChief']
    if master_chief and master_chief['source'] == 'api':
        lines.append(f"Master Chief (build, plan): own API {master_chief['baseURL']}, model {master_chief['model']}")
    elif master_chief:
        lines.append(f"Master Chief (build, plan): {master_chief['model']}")
    else:
        lines.append('Master Chief: model from opencode.jsonc')
    return '\n'.join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', help='loaded LM Studio instance ID (required only for ambiguous selection)')
    parser.add_argument('--prepare-only', action='store_true', help='prepare the config before opening the project in the desktop app')
    parser.add_argument('--reload', action='store_true', help='with --prepare-only: reload the current background OpenCode service')
    parser.add_argument('--opencode', default='opencode', help='OpenCode executable or command on PATH')
    parser.add_argument('arguments', nargs=argparse.REMAINDER, help='OpenCode arguments after --')
    args = parser.parse_args(argv)
    if args.reload and not args.prepare_only:
        parser.error('--reload requires --prepare-only')
    root = Path.cwd()
    try:
        executable = None
        if not args.prepare_only or args.reload:
            executable = find_opencode(args.opencode)
        model = prepare(root, args.model)
        print(describe(root, model), flush=True)
        if args.prepare_only:
            if args.reload:
                return subprocess.call([executable, 'reload'], cwd=root)
            print('Now open or reopen this project in OpenCode. Run preparation again after changing the loaded model.')
            return 0
        arguments = args.arguments[1:] if args.arguments[:1] == ['--'] else args.arguments
        if arguments[:1] == ['run'] and not any(a == '--standalone' or a == '--server' or a.startswith('--server=') for a in arguments):
            arguments = ['run', '--standalone', *arguments[1:]]
        # Expose launch facts to the agent so a private session does not reload another server.
        environment = os.environ.copy()
        environment['OPENCODE_KIT_ROOT'] = str(root.resolve())
        if model is not None:
            environment['OPENCODE_KIT_EXECUTORS'] = 'lmstudio'
            environment['OPENCODE_KIT_INSTANCE'] = model.id
        else:
            # No LM Studio instance is involved; do not leak one inherited from an outer launch.
            environment['OPENCODE_KIT_EXECUTORS'] = load_choices(root)['executors']['source']
            environment.pop('OPENCODE_KIT_INSTANCE', None)
        environment['OPENCODE_KIT_SERVER_MODE'] = 'standalone' if '--standalone' in arguments else 'shared'
        # Pass an argument list directly to the native CLI, without a shell.
        return subprocess.call([executable, *arguments], cwd=root, env=environment)
    except (ValueError, OSError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == '__main__':
    raise SystemExit(main())
